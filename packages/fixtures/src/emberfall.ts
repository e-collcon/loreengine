/** Generated bytes are the same every time; hash them once. */
const assetCache = new Map<string, { asset: NamedAsset; bytes: Uint8Array }>();
function namedAsset(g: GeneratedAsset): NamedAsset {
  let hit = assetCache.get(g.name);
  if (!hit) {
    const ref: NamedAsset['ref'] = { blobId: sha256HexSync(g.bytes), mime: g.mime, byteSize: g.bytes.length };
    if (g.width !== undefined) ref.width = g.width;
    if (g.height !== undefined) ref.height = g.height;
    if (g.durationMs !== undefined) ref.durationMs = g.durationMs;
    hit = { asset: { id: id('asset', g.name), name: g.name, ref }, bytes: g.bytes };
    assetCache.set(g.name, hit);
  }
  // A fresh copy each time: callers may mutate the project they were given.
  return { ...hit.asset, ref: { ...hit.asset.ref } };
}

/**
 * The bytes behind Emberfall's assets, by blob id: the generated SVG sources
 * and sounds. A client loads these into its blob store or asset resolver.
 */
export function emberfallBlobs(): Map<string, { bytes: Uint8Array; mime: string }> {
  buildEmberfall(); // fills the cache
  const out = new Map<string, { bytes: Uint8Array; mime: string }>();
  for (const { asset, bytes } of assetCache.values()) out.set(asset.ref.blobId, { bytes, mime: asset.ref.mime });
  return out;
}

